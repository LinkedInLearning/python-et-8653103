month_list = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sept", "Oct", "Nov", "Dec"]

def format_date(date):
  date = date.split("T")[0]
  date_parts = date.split("-")
  year = date_parts[0]
  month = int(date_parts[1])
  day = int(date_parts[2])
  return f"{day} of {month_list[month - 1]}, {year}"

